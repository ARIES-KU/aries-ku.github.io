// npm run pubs
// Finds each author's works in OpenAlex, then takes title / authors / venue / year from CrossRef by DOI
// (CrossRef is the record of what the publisher deposited; OpenAlex is used only to discover the works).
// Nothing in src/data/publications.json is typed by hand. Corrections go in src/data/pub-overrides.json.
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = async (p) => JSON.parse(await readFile(new URL(p, root), 'utf8'));
const UA = { 'User-Agent': 'ARIES-website publications script (https://aries-ku.github.io)' };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJSON(url, tries = 3) {
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(url, { headers: UA });
      if (res.status === 404) return null;
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      return await res.json();
    } catch (e) {
      if (i === tries - 1) throw e;
      await sleep(1500 * (i + 1));
    }
  }
}

const { authors, excludeTypes } = await read('src/data/authors.json');
const overrides = await read('src/data/pub-overrides.json');
const exclude = new Set(excludeTypes);

// 1. discover works in OpenAlex
const found = new Map();
for (const a of authors) {
  if (!a.openalex) { console.log(`skip ${a.name}: no OpenAlex id yet`); continue; }
  let cursor = '*';
  while (cursor) {
    const url = `https://api.openalex.org/works?filter=authorships.author.id:${a.openalex}&per-page=100&cursor=${encodeURIComponent(cursor)}` +
      '&select=id,doi,title,publication_year,type,primary_location,authorships';
    const page = await getJSON(url);
    for (const w of page.results) {
      if (exclude.has(w.type)) continue;
      const key = (w.doi || w.id).toLowerCase();
      if (!found.has(key)) found.set(key, w);
    }
    cursor = page.meta.next_cursor;
    await sleep(200);
  }
}
console.log(`OpenAlex: ${found.size} works after excluding ${[...exclude].join(', ')}`);

// 2. metadata from CrossRef where there is a DOI
const TYPE_LABEL = { 'journal-article': 'Journal', 'proceedings-article': 'Conference', 'book-chapter': 'Chapter', article: 'Journal', 'conference-paper': 'Conference' };
const items = [];
for (const [key, w] of found) {
  const doi = w.doi ? w.doi.replace('https://doi.org/', '') : null;
  let item = {
    title: w.title, year: w.publication_year, type: TYPE_LABEL[w.type] || w.type,
    venue: w.primary_location?.source?.display_name || '',
    authors: (w.authorships || []).map((x) => x.author.display_name),
    doi: w.doi || null, source: 'OpenAlex',
  };
  if (doi) {
    const cr = await getJSON(`https://api.crossref.org/works/${encodeURIComponent(doi)}`);
    await sleep(150);
    if (cr?.message) {
      const m = cr.message;
      if (exclude.has(m.type)) continue;
      const containers = m['container-title'] || [];
      const venue = m.type === 'proceedings-article'
        ? (m.event?.name || containers[containers.length - 1] || '')
        : (containers[0] || '');
      const year = (m.published?.['date-parts'] || m.issued?.['date-parts'] || [[item.year]])[0][0];
      item = {
        title: (m.title || [item.title])[0], year, type: TYPE_LABEL[m.type] || m.type,
        venue: venue || item.venue,
        authors: (m.author || []).map((x) => [x.given, x.family].filter(Boolean).join(' ') || x.name).filter(Boolean),
        doi: `https://doi.org/${m.DOI}`, source: 'CrossRef',
      };
      if (!item.authors.length) item.authors = (w.authorships || []).map((x) => x.author.display_name);
    }
  }
  const o = overrides[(item.doi || key).toLowerCase()];
  if (o?.hide) continue;
  if (o) item = { ...item, ...o.set };
  items.push(item);
}

// 3. drop same-title duplicates (e.g. a conference version and a journal version keep both; exact repeats do not)
const seen = new Set();
const unique = items.filter((it) => {
  const t = it.title.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (seen.has(t)) return false;
  seen.add(t); return true;
});
unique.sort((a, b) => b.year - a.year || a.title.localeCompare(b.title));

const bold = authors.map((a) => a.surname);
await writeFile(new URL('src/data/publications.json', root), JSON.stringify({
  generated: new Date().toISOString().slice(0, 10),
  note: 'Generated by scripts/fetch-publications.mjs. Do not edit by hand; use src/data/pub-overrides.json.',
  bold, items: unique,
}, null, 1) + '\n');
console.log(`wrote ${unique.length} publications (${unique.filter((i) => i.source === 'CrossRef').length} from CrossRef)`);
